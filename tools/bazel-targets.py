#!/usr/bin/env python3
"""Render native Rust BUILD files from the reviewed Linux crate graph."""

import argparse
import json
import subprocess
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).absolute().parent.parent
LIBRARY_KINDS = [["lib"], ["proc-macro"], ["cdylib"], ["cdylib", "rlib"]]
SHARED_CLIENTS = {"peios-reg", "peios-regman", "peios-evman"}
LOADS = """# Generated by tools/bazel-targets.py; edit build/crate-graph.json or its generator.
load("@crates//:crates.bzl", "aliases", "crate_deps")
load("@rules_rust//rust:defs.bzl", "rust_binary", "rust_library", "rust_proc_macro", "rust_shared_library", "rust_test", "rust_lint_config")
load("@rules_rust//cargo:defs.bzl", "cargo_build_script")
load("@rules_cc//cc:defs.bzl", "cc_import")
load("//build:checks.bzl", "shared_test")
package(default_visibility = ["//visibility:public"])
exports_files(["Cargo.toml"])
"""


@dataclass(frozen=True)
class Expression:
    """An already-formed Starlark expression rather than a quoted string."""

    text: str


def literal(value: Any) -> str:
    """Serialize generator-owned values using Starlark boolean and string syntax."""
    if isinstance(value, Expression):
        return value.text
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, dict):
        return "{" + ", ".join(f"{literal(k)}: {literal(v)}" for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(literal(item) for item in value) + "]"
    return json.dumps(value)


def rule(rule_name: str, **attributes: Any) -> str:
    """Emit one rule; the pinned buildifier applies canonical layout afterward."""
    return (
        rule_name
        + "("
        + ", ".join(f"{key}={literal(value)}" for key, value in attributes.items())
        + ")\n"
    )


def dependencies(crate: dict, kind: str, *, procedural: bool = False) -> Expression:
    """Keep local and external dependencies separate, including procedural macros."""
    prefix = "proc_" if procedural else ""
    group = crate["deps"][kind]
    external = literal(sorted(set(group[prefix + "external"])))
    local_targets = set(group[prefix + "local"])
    # Cargo builds this preload-only cdylib without linking it into stdbuf.
    # In Bazel it is a separate runtime/package input, not a native link dependency.
    if crate.get("name") == "pu_stdbuf" and kind == "normal":
        local_targets.discard("//src/uu/stdbuf/src/libstdbuf:library")
    local = literal(sorted(local_targets))
    return Expression(f"crate_deps({external}) + {local}")


def source_groups(crate: dict) -> str:
    """Exclude build output and avoid walking undeclared root caches."""
    patterns = (
        ["**"]
        if crate["path"]
        else [
            "*",
            "src/**/*.rs",
            "tests/**",
            "third-party/**",
            "docs/**",
            ".github/**",
            ".cargo/**",
        ]
    )
    exclude = [
        "target/**",
        "out/**",
        "**/__pycache__/**",
        "bazel-*/**",
        ".git/**",
        ".ci-sdk/**",
        "docs/learn/dist/**",
    ]
    sources = Expression(f"glob({literal(patterns)}, exclude={literal(exclude)})")
    return rule("filegroup", name="sources", srcs=sources) + rule(
        "filegroup", name="locales", srcs=Expression('glob(["locales/*.ftl"], allow_empty=True)')
    )


def build_script(crate: dict, target: dict | None) -> str:
    """Give uucore all declared locales; stdbuf uses its separate native target."""
    if target is None:
        return ""
    data = Expression('glob(["locales/**"], allow_empty=True)')
    environment = {}
    if crate["name"] == "uucore":
        data = ["//:all-locales"]
        environment = {"LANG": "en_US.UTF-8"}
    return rule(
        "cargo_build_script",
        name="build-script",
        srcs=[target["source"]],
        crate_features=Expression("_FEATURES"),
        edition=crate["edition"],
        version=crate["version"],
        compile_data=["Cargo.toml"],
        data=data,
        build_script_env=environment,
        deps=dependencies(crate, "build"),
        proc_macro_deps=dependencies(crate, "build", procedural=True),
        aliases=Expression("_ALIASES"),
    )


def lint_configuration(crate: dict) -> str:
    """Keep Bazel lint levels and priority ordering aligned with the Cargo manifest."""
    manifest = tomllib.loads((ROOT / crate["path"] / "Cargo.toml").read_text())
    settings = manifest.get("lints", {})
    if settings.get("workspace"):
        settings = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["lints"]
    features = set(manifest.get("features", {}))
    tables = [manifest.get("dependencies", {})]
    tables.extend(target.get("dependencies", {}) for target in manifest.get("target", {}).values())
    for table in tables:
        features.update(
            name
            for name, value in table.items()
            if isinstance(value, dict) and value.get("optional")
        )
    if not crate["path"]:
        # Retired POSIX fixture branches remain disabled: these names are not
        # Cargo features and are never enabled in the production feature set.
        features.update(["chmod", "chown"])
    # Cargo supplies these cfg names even when a feature or test is disabled.
    attributes = {"rustc_check_cfg": {"test": [], "feature": sorted(features)}}
    if crate["name"] == "pu_stty":
        # cfg_aliases declares this platform name in stty's build script.
        attributes["rustc_check_cfg"]["bsd"] = []
    for cargo_name, bazel_name in [("rust", "rustc"), ("clippy", "clippy"), ("rustdoc", "rustdoc")]:
        entries = settings.get(cargo_name, {})
        ordered = sorted(
            entries,
            key=lambda key: (
                entries[key].get("priority", 0) if isinstance(entries[key], dict) else 0,
                key,
            ),
        )
        attributes[bazel_name] = {
            key: entries[key]["level"] if isinstance(entries[key], dict) else entries[key]
            for key in ordered
        }
    # Cargo metadata lints invoke Cargo, which is intentionally absent from
    # declared Bazel compile actions. The graph resolver checks locked metadata.
    if "cargo" in attributes["clippy"]:
        attributes["clippy"]["cargo"] = "allow"
    check_cfg = settings.get("rust", {}).get("unexpected_cfgs", {})
    if isinstance(check_cfg, dict) and check_cfg.get("check-cfg"):
        # These are the workspace's declared custom cfgs. Fail rather than silently
        # dropping a newly added configuration expression during regeneration.
        supported = {
            "cfg(fuzzing)": ("fuzzing", []),
            'cfg(target_os, values("cygwin"))': ("target_os", ["cygwin"]),
            "cfg(wasi_runner)": ("wasi_runner", []),
        }
        attributes["rustc_check_cfg"].update(supported[item] for item in check_cfg["check-cfg"])
    return rule("rust_lint_config", name="lints", **attributes)


def common_attributes(crate: dict, has_build_script: bool) -> dict:
    """Describe shared compiler inputs for one crate's libraries and binaries."""
    deps = dependencies(crate, "normal").text
    if has_build_script:
        deps += ' + [":build-script"]'
    links = []
    if crate["name"] in SHARED_CLIENTS:
        links = ["//crates/lib" + crate["name"].removeprefix("peios-") + ":link"]
    return {
        "srcs": Expression('glob(["src/**/*.rs"])'),
        "compile_data": Expression(
            '["Cargo.toml"] + glob(["locales/**", "src/**/*.md", "src/**/*.ftl", "stubs/**"], allow_empty=True)'
        ),
        "crate_features": Expression("_FEATURES"),
        "edition": crate["edition"],
        "version": crate["version"],
        "aliases": Expression("_ALIASES"),
        "rustc_env": {
            "LIBSTDBUF_DIR": "/usr/lib/x86_64-linux-peios/peiosutils",
            "PATH": "/usr/bin:/bin",
        },
        "lint_config": ":lints",
        "proc_macro_deps": dependencies(crate, "normal", procedural=True),
        "deps": Expression(deps),
        **({"link_deps": links} if links else {}),
    }


def shared_library(crate: dict, target: dict, common: dict) -> str:
    """Export an ABI-major SONAME and carry its actual runtime file into runfiles."""
    soname = "lib" + target["name"] + ".so.1"
    return (
        rule(
            "rust_shared_library",
            name="shared",
            crate_name=target["name"],
            crate_root=target["source"],
            **common,
            rustc_flags=["-Clink-arg=-Wl,-soname," + soname],
        )
        + rule(
            "genrule",
            name="soname",
            srcs=[":shared"],
            outs=[soname],
            cmd="cp $(location :shared) $@",
        )
        + rule(
            "cc_import",
            name="link",
            interface_library=":shared",
            shared_library=":soname",
            deps=["@peios_sdk//:peios"] if crate["name"] == "libreg" else [],
        )
    )


def unit_tests(crate: dict) -> str:
    """Run native unit binaries with only their required shared-library search paths."""
    libraries = ["@peios_sdk//:library", "@peios_sdk//:auth-library"]
    if crate["path"].startswith("crates/") and crate["name"] not in {
        "registry-docs",
        "libreg",
        "peios-reg",
    }:
        libraries = []
    if crate["name"] in SHARED_CLIENTS:
        libraries.append("//crates/lib" + crate["name"].removeprefix("peios-") + ":soname")
    extra = {"data": [":unit-locales"]} if crate["name"] == "uucore" else {}
    return rule(
        "rust_test",
        name="unit-binary",
        **extra,
        crate=":library",
        lint_config=":lints",
        crate_features=Expression("_FEATURES"),
        tags=["manual"],
        deps=dependencies(crate, "dev"),
        proc_macro_deps=dependencies(crate, "dev", procedural=True),
    ) + rule("shared_test", name="unit-tests", binary=":unit-binary", libraries=libraries)


def render_crate(crate: dict) -> str:
    """Render one workspace package without invoking Cargo to build it."""
    targets = crate["targets"]
    library = next((target for target in targets if target["kind"] in LIBRARY_KINDS), None)
    script = next((target for target in targets if target["kind"] == ["custom-build"]), None)
    if crate["name"] == "pu_stdbuf":
        script = None
    text = LOADS + source_groups(crate) + lint_configuration(crate)
    if crate["name"] == "uucore":
        text = 'load("//build:locales.bzl", "locale_tree")\n' + text
        text += rule("locale_tree", name="unit-locales", srcs=["//:all-locales"])
    text += "_FEATURES = " + literal(crate["features"]) + "\n"
    text += "_ALIASES = aliases() | " + literal(crate["aliases"]) + "\n"
    text += build_script(crate, script)
    common = common_attributes(crate, script is not None)
    if library:
        kind = "lib" if library["kind"] == ["cdylib", "rlib"] else library["kind"][0]
        name = {
            "lib": "rust_library",
            "proc-macro": "rust_proc_macro",
            "cdylib": "rust_shared_library",
        }[kind]
        text += rule(
            name,
            name="library",
            crate_name=library["name"].replace("-", "_"),
            crate_root=library["source"],
            **common,
        )
        if library["kind"] == ["cdylib", "rlib"]:
            text += shared_library(crate, library, common)
        if library.get("test") and kind == "lib":
            text += unit_tests(crate)
    for target in targets:
        if target["kind"] != ["bin"]:
            continue
        attributes = common.copy()
        if library:
            attributes["deps"] = Expression(attributes["deps"].text + ' + [":library"]')
        text += rule(
            "rust_binary",
            name=target["name"],
            crate_name=target["name"].replace("-", "_"),
            crate_root=target["source"],
            **attributes,
        )
    return text


def integration_tests(crate: dict) -> str:
    """Give the inherited harness its expected executable name, fixtures and version."""
    merged = {"deps": {"test": {}}}
    for key in ["local", "external", "proc_local", "proc_external"]:
        merged["deps"]["test"][key] = crate["deps"]["normal"][key] + crate["deps"]["dev"][key]
    return (
        rule(
            "rust_test",
            name="integration-binary",
            crate_name="tests",
            lint_config=":lints",
            crate_root="tests/tests.rs",
            srcs=Expression('glob(["tests/**/*.rs"])'),
            compile_data=[":sources"],
            data=Expression(
                '[":peiosutils", ":uudoc", ":libstdbuf.so", ":locales-runtime"] + glob(["tests/fixtures/**"])'
            ),
            crate_features=Expression("_FEATURES"),
            edition=crate["edition"],
            version=crate["version"],
            rustc_env={"CARGO_BIN_EXE_peiosutils": "$(rootpath :peiosutils)"},
            aliases=Expression("_ALIASES"),
            deps=dependencies(merged, "test"),
            proc_macro_deps=dependencies(merged, "test", procedural=True),
            tags=["manual"],
        )
        + rule(
            "shared_test",
            name="integration-tests",
            binary=":integration-binary",
            utility=":peiosutils",
            libraries=["@peios_sdk//:library", "@peios_sdk//:auth-library"],
            args=["--skip", "gnu"],
            tags=["external", "no-remote"],
            timeout="long",
        )
        + rule(
            "genrule",
            name="stdbuf-runtime",
            srcs=["//src/uu/stdbuf/src/libstdbuf:library"],
            outs=["libstdbuf.so"],
            cmd="cp $< $@",
        )
    )


def render_root(graph: list[dict], root: dict) -> str:
    """Keep handwritten package and quality targets outside generated crate definitions."""
    text = render_crate(root)
    text += rule(
        "filegroup",
        name="all-locales",
        srcs=["//" + crate["path"] + ":locales" for crate in graph if crate["path"]],
    )
    text += rule(
        "filegroup",
        name="all-sources",
        srcs=[":sources", "//build:sources", "//tools:sources", "//vendor:sources"]
        + ["//" + crate["path"] + ":sources" for crate in graph if crate["path"]],
    )
    text += integration_tests(root)
    supplement = (ROOT / "build/root.BUILD.bazel").read_text(encoding="utf-8").splitlines()
    # Supplement loads deliberately occupy one line each so they can precede rule calls.
    loads = [line for line in supplement if line.startswith("load(")]
    body = [line for line in supplement if not line.startswith("load(")]
    return "\n".join(loads) + "\n" + text + "\n" + "\n".join(body) + "\n"


def main() -> None:
    """Write generated targets, or fail if any checked-in target differs."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--buildifier", default="buildifier")
    args = parser.parse_args()
    graph = json.loads((ROOT / "build/crate-graph.json").read_text(encoding="utf-8"))
    failed = []
    for crate in graph:
        text = render_crate(crate) if crate["path"] else render_root(graph, crate)
        formatted = subprocess.check_output(
            [args.buildifier, "-type=build", "-lint=fix", "-warnings=load"],
            input=text,
            text=True,
        )
        path = ROOT / crate["path"] / "BUILD.bazel"
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != formatted:
                failed.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(formatted, encoding="utf-8")
    if failed:
        parser.exit(1, "Regenerate native targets: " + ", ".join(failed) + "\n")


if __name__ == "__main__":
    main()
